  float d_left; // distance capteur gauche
  float d_front; // distance capteur avant
  float prev_d_left[5] = {0,0,0,0,0}; // précédent distance capteur gauche
  enum {
	MODE_INIT,
	MODE_CLIMB,
	MODE_STAIR,
  MODE_FLAT
} mode = MODE_INIT;


  /* USER CODE END 2 */

